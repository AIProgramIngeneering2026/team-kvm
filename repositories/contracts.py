
from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol

from core.job import Job, JobStatus


class IdempotencyConflictError(Exception):
    """Ошибка повторного использования ключа идемпотентности.

    Возникает, когда клиент повторно использует Idempotency-Key,
    но передаёт другие данные запроса.
    """

    code = "IDEMPOTENCY_KEY_CONFLICT"

    def __init__(self) -> None:
        super().__init__("Idempotency-Key was already used for another request.")


class ConcurrentJobUpdateError(Exception):
    """Ошибка конкурентного изменения задания.

    Возникает, если состояние Job в хранилище изменилось
    после того, как оно было прочитано.

    Запрещает перезаписывать более актуальное состояние
    устаревшими данными.
    """

    code = "CONCURRENT_JOB_UPDATE"

    def __init__(self, job_id: str) -> None:
        self.job_id = job_id
        super().__init__(f"Job {job_id} was updated concurrently.")


@dataclass(frozen=True, slots=True)
class CreateStoredJobOutcome:
    """Результат создания задания в хранилище.

    job — созданное или найденное задание.

    replayed=False — в хранилище создана новая Job.

    replayed=True — задание с таким ключом идемпотентности
    и содержимым запроса уже существует.
    Новая Job при этом не создаётся.
    """

    job: Job
    replayed: bool


@dataclass(frozen=True, slots=True)
class StoredJobPage:
    """Страница заданий, полученных из хранилища.

    items — задания текущей страницы с учётом фильтров.

    total — общее количество заданий, соответствующих фильтрам,
    до применения limit и offset.
    """

    items: tuple[Job, ...]
    total: int


class JobRepositoryPort(Protocol):
    """Интерфейс взаимодействия JobService и JobRepository.

    Определяет методы, которые должна предоставлять
    конкретная реализация репозитория.

    Реализация на SQLite должна:
    - Выполнять каждую операцию записи в транзакции.
    - Восстанавливать Job из базы с сохранением исходного ID,
      состояния, временных меток, результата и ошибки.
    - Обеспечивать атомарность операций и защиту
      от конкурентного изменения данных.

    Для модульных тестов допускается использовать
    реализацию репозитория в оперативной памяти.

    Интерфейс не должен зависеть от SQLite,
    SQLAlchemy или других библиотек работы с БД.
    """

    def create_or_get(
        self,
        *,
        client_id: str,
        job: Job,
        idempotency_key: str | None,
        request_hash: str,
    ) -> CreateStoredJobOutcome:
        """Атомарно создать новую Job или вернуть существующую.

        Ключ идемпотентности уникален в рамках одного клиента:
        (client_id, idempotency_key).

        Уникальность должна обеспечиваться ограничением UNIQUE
        или уникальным индексом в SQLite для ненулевых ключей.

        Правила работы:

        1. idempotency_key=None:
           Всегда создаётся новое задание.

        2. Ключ ещё не использовался:
           Новая Job в состоянии created, ключ идемпотентности
           и хеш запроса сохраняются в одной транзакции.

        3. Ключ уже существует, хеш запроса совпадает:
           Возвращается сохранённая Job с replayed=True.
           Повторное выполнение задания не запускается.

        4. Ключ уже существует, но хеш запроса отличается:
           Вызывается IdempotencyConflictError.

        request_hash должен вычисляться на основании
        выбранной операции и точного содержимого файла.

        Имя файла, MIME-тип и ключ авторизации клиента
        не должны влиять на вычисление request_hash.

        При одновременных запросах с одинаковым ключом
        должна создаваться только одна Job.
        """
        ...

    def get(self, *, client_id: str, job_id: str) -> Job | None:
        """Получить задание конкретного клиента по идентификатору.

        Возвращает объект Job, если задание существует
        и принадлежит указанному клиенту.

        Возвращает None, если задание отсутствует
        или принадлежит другому клиенту.

        Репозиторий не должен раскрывать информацию
        о существовании заданий других клиентов.
        """
        ...

    def list_jobs(
        self,
        *,
        client_id: str,
        status: JobStatus | None = None,
        operation: str | None = None,
        limit: int = 20,
        offset: int = 0,
    ) -> StoredJobPage:
        """Получить историю заданий конкретного клиента.

        Возвращает задания от новых к старым.

        client_id — идентификатор владельца заданий.

        status — необязательный фильтр по состоянию Job.

        operation — необязательный фильтр по типу операции.

        limit — максимальное количество заданий на странице.

        offset — количество записей, которые нужно пропустить.

        Сначала применяются фильтры, затем limit и offset.

        Поле total содержит общее количество записей,
        соответствующих фильтрам, без учёта пагинации.
        """
        ...

    def save_transition(
        self,
        *,
        job: Job,
        expected_status: JobStatus,
    ) -> None:
        """Атомарно сохранить изменение состояния Job.

        Переход состояния должен быть предварительно
        выполнен и проверен доменной моделью Job.

        В ОДНОЙ транзакции необходимо:

        1. Проверить, что сохранённое состояние задания
           совпадает с expected_status.

        2. Записать новое состояние job.status.

        3. Сохранить job.result или job.error.

        4. Обновить временную метку updated_at.

        5. Сохранить историю изменений, если она хранится в БД.

        Для защиты от конкурентных изменений можно
        использовать условный SQL-запрос:

        UPDATE jobs
        SET ...
        WHERE id = ? AND status = ?

        Если подходящая запись не найдена, необходимо
        вызвать ConcurrentJobUpdateError.

        В этом случае никакие изменения не сохраняются.

        Устаревший исполнитель не должен иметь возможности
        перезаписать уже завершённое задание.

        ВАЖНО:
        Нельзя напрямую изменять внутреннее поле job._status
        для выполнения перехода состояния.

        Допустимые переходы должны выполняться через методы
        доменной модели: start(), complete() и fail().
        """
        ...

    def list_unfinished(self) -> tuple[Job, ...]:
        """Получить все незавершённые задания после перезапуска.

        Возвращает Job в состояниях created и running
        независимо от того, какому клиенту они принадлежат.

        Правила восстановления:

        - created:
          Задание повторно ставится в очередь на выполнение.

        - running:
          Вызывается метод recover_after_restart(),
          который переводит задание в failed с ошибкой
          WORKER_INTERRUPTED.

          Переход running → failed сохраняется
          атомарно через репозиторий.

        - done и failed:
          Завершённые задания автоматически не перезапускаются.

        Метод используется JobRunner при запуске приложения
        для восстановления состояния после перезапуска сервиса.
        """
        ...
